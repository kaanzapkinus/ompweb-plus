// Regenerate every OMPWeb mark from public/omp-web-logo.svg:
//   node scripts/generate-brand-assets.mjs
// Normal / Apple icons are opaque. Maskable artwork is inset inside the
// central 80%-diameter safe circle; the full-bleed background is never inset.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = new URL("../", import.meta.url);
const source = await readFile(new URL("public/omp-web-logo.svg", root), "utf8");
const inner = source.slice(source.indexOf(">") + 1, source.lastIndexOf("</svg>"));
const mark = source.match(/<g id="mark"[^>]*>[\s\S]*?<\/g>/)?.[0];
const texture = source.match(/<g id="texture"[^>]*>[\s\S]*?<\/g>/)?.[0];
if (!mark || !texture) throw new Error("SVG master must contain mark and texture groups");

const svg = (body, viewBox = "0 0 512 512") =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="${viewBox}">${body}</svg>\n`;
const maskable = source.replace(mark, `<g transform="translate(51.2 51.2) scale(.8)">${mark}</g>`)
  .replace(texture, `<g transform="translate(51.2 51.2) scale(.8)">${texture}</g>`);
const png = (artwork, size, opaque = true) => {
  let image = sharp(Buffer.from(artwork), { density: 288 }).resize(size, size);
  if (opaque) image = image.flatten({ background: "#161616" });
  return image.png({ compressionLevel: 9 }).toBuffer();
};
const save = (path, content) => writeFile(new URL(path, root), content);

for (const [path, size, artwork] of [
  ["public/icon.png", 512, source],
  ["public/icon-192.png", 192, source],
  ["public/icon-maskable-192.png", 192, maskable],
  ["public/icon-maskable-512.png", 512, maskable],
  ["public/apple-touch-icon.png", 180, source],
  ["public/favicon-16.png", 16, source],
  ["public/favicon-32.png", 32, source],
]) {
  await save(path, await png(artwork, size));
}
await save("public/icon.svg", source);
await save("app/icon.svg", source);

// PNG-compressed ICO entries work in browsers and the existing Windows tray.
// Each frame has an explicit opaque alpha channel and a 32-bit directory entry.
const sizes = [16, 32, 48, 256];
const frames = [];
for (const size of sizes) {
  frames.push(await sharp(Buffer.from(source), { density: 288 })
    .resize(size, size).flatten({ background: "#161616" }).ensureAlpha().png().toBuffer());
}
const directory = Buffer.alloc(6 + sizes.length * 16);
directory.writeUInt16LE(1, 2);
directory.writeUInt16LE(sizes.length, 4);
let offset = directory.length;
for (const [index, size] of sizes.entries()) {
  const entry = 6 + index * 16;
  directory[entry] = size === 256 ? 0 : size;
  directory[entry + 1] = size === 256 ? 0 : size;
  directory.writeUInt16LE(1, entry + 4);
  directory.writeUInt16LE(32, entry + 6);
  directory.writeUInt32LE(frames[index].length, entry + 8);
  directory.writeUInt32LE(offset, entry + 12);
  offset += frames[index].length;
}
const ico = Buffer.concat([directory, ...frames]);
await save("app/favicon.ico", ico);
await save("public/omp-web.ico", ico);

// Platform monochrome marks retain the same chat outline and >_ cutouts,
// without a tile or halftone that would turn into a solid notification badge.
const monochrome = (fill) => svg(mark.replace('id="mark"', "").replace("#d2d2ce", fill), "64 80 384 384");
await save("public/badge-96.png", await png(monochrome("#ffffff"), 96, false));
const tray = monochrome("#000000").replace('width="512" height="512"', 'width="18" height="18"');
await save("public/trayTemplate.svg", tray);
await save("public/trayTemplate.png", await png(tray, 36, false));

// Inline the canonical vectors: no external request, fallback, gradient IDs,
// runtime SVG parsing, or separate hand-maintained UI artwork.
const jsx = inner.trim().replace(/\s+id="[^"]*"/g, "").replaceAll("fill-rule", "fillRule");
await save("components/OmpWebLogo.tsx", `// Generated by scripts/generate-brand-assets.mjs from public/omp-web-logo.svg.
export default function OmpWebLogo({
  size = 20,
  label = "OMPWeb logo",
}: {
  size?: number;
  label?: string;
}) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 512 512"
      role="img"
      aria-label={label}
      style={{ display: "block", flexShrink: 0 }}
    >
      ${jsx.replaceAll("\n", "\n      ")}
    </svg>
  );
}
`);
console.log(`Generated OMPWeb UI, PWA, Apple, favicon, badge and tray assets from ${fileURLToPath(new URL("public/omp-web-logo.svg", root))}`);
